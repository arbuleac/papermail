#!/usr/bin/env bash
# Assemble dist/Paper.app from the SwiftPM build. Usage: scripts/build-app.sh [debug|release]
set -euo pipefail
CONFIG="${1:-debug}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

swift build -c "$CONFIG" --product Paper
BIN_DIR="$(swift build -c "$CONFIG" --show-bin-path)"

# The executable says which SDK generation it is built for (Package.swift, `sdkStamp`), which is what macOS goes by
# when it chooses AppKit's behaviour and the window chrome. Without the stamp SwiftPM writes the deployment target
# there, and the app would run as one built for macOS 15 while its tests run the current AppKit
# (docs/ARCHITECTURE.md, "Testing").
STAMP="$(xcrun vtool -show-build "$BIN_DIR/Paper" | awk '$1 == "sdk" { print $2; exit }')"
MINOS="$(xcrun vtool -show-build "$BIN_DIR/Paper" | awk '$1 == "minos" { print $2; exit }')"
SDK="$(xcrun --sdk macosx --show-sdk-version 2>/dev/null || true)"
if [ -z "$STAMP" ] || [ "$STAMP" = "$MINOS" ]; then
  echo "error: Paper is stamped for SDK '${STAMP:-none}', its deployment target; Package.swift's sdkStamp did not reach the linker" >&2
  exit 1
fi
if [ -n "$SDK" ] && [ "${SDK%%.*}" != "${STAMP%%.*}" ]; then
  echo "warning: Paper is stamped for the macOS ${STAMP%%.*} SDK and the installed SDK is $SDK: the tests run AppKit as built for ${SDK%%.*}, the app as built for ${STAMP%%.*}. Look at the app with sdkStamp raised, then raise it in Package.swift" >&2
fi
APP="$ROOT/dist/Paper.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN_DIR/Paper" "$APP/Contents/MacOS/Paper"
cp "$ROOT/Resources/Info.plist" "$APP/Contents/Info.plist"
# Crash reporting (docs/ANALYTICS-AND-REPORTS.md): the Sentry project's DSN, from SENTRY_DSN or the untracked file
# Resources/SentryDSN. Without one the app sends no crash reports.
DSN="${SENTRY_DSN:-}"
if [ -z "$DSN" ] && [ -f "$ROOT/Resources/SentryDSN" ]; then
  DSN="$(tr -d '[:space:]' < "$ROOT/Resources/SentryDSN")"
fi
if [ -n "$DSN" ]; then
  plutil -replace SentryDSN -string "$DSN" "$APP/Contents/Info.plist"
else
  echo "note: no Sentry DSN (SENTRY_DSN or Resources/SentryDSN); this build sends no crash reports" >&2
fi
# Analytics (docs/ANALYTICS-AND-REPORTS.md): the TelemetryDeck app's ID, from TELEMETRYDECK_APP_ID or the untracked file
# Resources/TelemetryDeckAppID. Without one the app sends no analytics; with neither this nor a DSN, Settings › General
# says Analytics and reports is not set up in this build.
APP_ID="${TELEMETRYDECK_APP_ID:-}"
if [ -z "$APP_ID" ] && [ -f "$ROOT/Resources/TelemetryDeckAppID" ]; then
  APP_ID="$(tr -d '[:space:]' < "$ROOT/Resources/TelemetryDeckAppID")"
fi
if [ -n "$APP_ID" ]; then
  plutil -replace TelemetryDeckAppID -string "$APP_ID" "$APP/Contents/Info.plist"
else
  echo "note: no TelemetryDeck app ID (TELEMETRYDECK_APP_ID or Resources/TelemetryDeckAppID); this build sends no analytics" >&2
fi
# The build's debug symbols beside the bundle, so its crash reports can be symbolicated (scripts/upload-dsyms.sh).
DSYM="$ROOT/dist/Paper.app.dSYM"
rm -rf "$DSYM"
if xcrun --find dsymutil >/dev/null 2>&1; then
  xcrun dsymutil "$BIN_DIR/Paper" -o "$DSYM" >/dev/null 2>&1 \
    || echo "warning: dsymutil failed; crash reports from this build will show addresses, not function names" >&2
fi
# SwiftPM resource bundles (if any target declares resources) sit next to the binary.
for bundle in "$BIN_DIR"/*.bundle; do
  [ -e "$bundle" ] && cp -R "$bundle" "$APP/Contents/Resources/" || true
done
# The Iron Gall accent (spec §3.1) and the app icon (§5.42). Resources/Assets.xcassets is generated by
# scripts/tools/quire-tokens.swift; Resources/AppIcon.icon (an Icon Composer document) and Resources/AppIcon.icns
# by scripts/tools/app-icon.swift. actool ships with Xcode, not the command line tools; without it the app still
# runs, with the system accent on native controls (menu highlights, default buttons) instead of Iron Gall and
# the .icns alone as its icon (no dark or tinted appearance on macOS 26 and later).
HAS_ICON_DOCUMENT=0
if [ -d "$ROOT/Resources/Assets.xcassets" ]; then
  if xcrun --find actool >/dev/null 2>&1; then
    # A private directory, removed on every exit path, so a failing actool leaves nothing in $TMPDIR.
    ASSET_DIR="$(mktemp -d -t paper-assets)"
    trap 'rm -rf "$ASSET_DIR"' EXIT
    ASSET_PLIST="$ASSET_DIR/partial.plist"
    if [ -d "$ROOT/Resources/AppIcon.icon" ]; then
      # The icon document gives macOS 26 and later the default, dark and tinted icon; a macOS app icon set
      # cannot carry the last two.
      xcrun actool "$ROOT/Resources/Assets.xcassets" "$ROOT/Resources/AppIcon.icon" \
        --compile "$APP/Contents/Resources" \
        --platform macosx \
        --minimum-deployment-target 15.0 \
        --accent-color AccentColor \
        --app-icon AppIcon --include-all-app-icons \
        --output-partial-info-plist "$ASSET_PLIST" \
        --errors --warnings >/dev/null
      HAS_ICON_DOCUMENT=1
    else
      xcrun actool "$ROOT/Resources/Assets.xcassets" \
        --compile "$APP/Contents/Resources" \
        --platform macosx \
        --minimum-deployment-target 15.0 \
        --accent-color AccentColor \
        --output-partial-info-plist "$ASSET_PLIST" \
        --errors --warnings >/dev/null
    fi
    rm -rf "$ASSET_DIR"
    /usr/libexec/PlistBuddy -c "Add :NSAccentColorName string AccentColor" "$APP/Contents/Info.plist" >/dev/null 2>&1 \
      || /usr/libexec/PlistBuddy -c "Set :NSAccentColorName AccentColor" "$APP/Contents/Info.plist"
  else
    echo "warning: xcrun actool not found (install Xcode); the bundle has no AccentColor asset and no dark or tinted icon" >&2
  fi
fi
# Settings › OAuth links to the setup guide (“How to create these…”).
cp "$ROOT/docs/OAUTH-SETUP.md" "$APP/Contents/Resources/OAUTH-SETUP.md"
# The drawn .icns replaces the one actool renders from the icon document: it carries every size up to 1024 px on
# the macOS 15 grid, and it is the icon wherever the asset catalog is not read. Where Assets.car holds AppIcon, the
# system reads CFBundleIconName first on every supported macOS: macOS 15 shows actool's flat renderings of the
# document, not this file (spec §5.42).
if [ -f "$ROOT/Resources/AppIcon.icns" ]; then
  cp "$ROOT/Resources/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"
  /usr/libexec/PlistBuddy -c "Add :CFBundleIconFile string AppIcon" "$APP/Contents/Info.plist" >/dev/null 2>&1 || true
fi
if [ "$HAS_ICON_DOCUMENT" = 1 ]; then
  /usr/libexec/PlistBuddy -c "Add :CFBundleIconName string AppIcon" "$APP/Contents/Info.plist" >/dev/null 2>&1 \
    || /usr/libexec/PlistBuddy -c "Set :CFBundleIconName AppIcon" "$APP/Contents/Info.plist"
fi
# Ad-hoc signature so Keychain, notifications and WebKit behave like a real app. Replace with a
# Developer ID identity for distribution: CODESIGN_IDENTITY="Developer ID Application: …" scripts/build-app.sh release
codesign --force --sign "${CODESIGN_IDENTITY:--}" --entitlements "$ROOT/Resources/Paper.entitlements" "$APP" >/dev/null
echo "$APP"
