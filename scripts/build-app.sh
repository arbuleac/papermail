#!/usr/bin/env bash
# Assemble dist/SuperSparrow.app from the SwiftPM build. Usage: scripts/build-app.sh [debug|release]
set -euo pipefail
CONFIG="${1:-debug}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

swift build -c "$CONFIG" --product SuperSparrow
BIN_DIR="$(swift build -c "$CONFIG" --show-bin-path)"
APP="$ROOT/dist/SuperSparrow.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN_DIR/SuperSparrow" "$APP/Contents/MacOS/SuperSparrow"
cp "$ROOT/Resources/Info.plist" "$APP/Contents/Info.plist"
# SwiftPM resource bundles (if any target declares resources) sit next to the binary.
for bundle in "$BIN_DIR"/*.bundle; do
  [ -e "$bundle" ] && cp -R "$bundle" "$APP/Contents/Resources/" || true
done
# The Iron Gall accent (spec §3.1) and the app icon (§5.42). Resources/Assets.xcassets is generated by
# scripts/tools/quire-tokens.swift; Resources/AppIcon.icon (an Icon Composer document) and Resources/AppIcon.icns
# by scripts/tools/app-icon.swift. actool ships with Xcode, not the command line tools; without it the app still
# runs, with the system accent on native controls (menu highlights, default buttons) instead of Iron Gall and
# the .icns alone as its icon (no dark or tinted appearance on macOS 26 and later).
HAS_ICON_DOCUMENT=0
if [ -d "$ROOT/Resources/Assets.xcassets" ]; then
  if xcrun --find actool >/dev/null 2>&1; then
    # A private directory, removed on every exit path, so a failing actool leaves nothing in $TMPDIR.
    ASSET_DIR="$(mktemp -d -t supersparrow-assets)"
    trap 'rm -rf "$ASSET_DIR"' EXIT
    ASSET_PLIST="$ASSET_DIR/partial.plist"
    if [ -d "$ROOT/Resources/AppIcon.icon" ]; then
      # The icon document gives macOS 26 and later the default, dark and tinted icon; a macOS app icon set
      # cannot carry the last two.
      xcrun actool "$ROOT/Resources/Assets.xcassets" "$ROOT/Resources/AppIcon.icon" \
        --compile "$APP/Contents/Resources" \
        --platform macosx \
        --minimum-deployment-target 15.0 \
        --accent-color AccentColor \
        --app-icon AppIcon --include-all-app-icons \
        --output-partial-info-plist "$ASSET_PLIST" \
        --errors --warnings >/dev/null
      HAS_ICON_DOCUMENT=1
    else
      xcrun actool "$ROOT/Resources/Assets.xcassets" \
        --compile "$APP/Contents/Resources" \
        --platform macosx \
        --minimum-deployment-target 15.0 \
        --accent-color AccentColor \
        --output-partial-info-plist "$ASSET_PLIST" \
        --errors --warnings >/dev/null
    fi
    rm -rf "$ASSET_DIR"
    /usr/libexec/PlistBuddy -c "Add :NSAccentColorName string AccentColor" "$APP/Contents/Info.plist" >/dev/null 2>&1 \
      || /usr/libexec/PlistBuddy -c "Set :NSAccentColorName AccentColor" "$APP/Contents/Info.plist"
  else
    echo "warning: xcrun actool not found (install Xcode); the bundle has no AccentColor asset and no dark or tinted icon" >&2
  fi
fi
# Settings › OAuth links to the setup guide (“How to create these…”).
cp "$ROOT/docs/OAUTH-SETUP.md" "$APP/Contents/Resources/OAUTH-SETUP.md"
# The drawn .icns replaces the one actool renders from the icon document: it carries every size up to 1024 px on
# the macOS 15 grid, and it is the icon wherever the asset catalog is not read.
if [ -f "$ROOT/Resources/AppIcon.icns" ]; then
  cp "$ROOT/Resources/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"
  /usr/libexec/PlistBuddy -c "Add :CFBundleIconFile string AppIcon" "$APP/Contents/Info.plist" >/dev/null 2>&1 || true
fi
if [ "$HAS_ICON_DOCUMENT" = 1 ]; then
  /usr/libexec/PlistBuddy -c "Add :CFBundleIconName string AppIcon" "$APP/Contents/Info.plist" >/dev/null 2>&1 \
    || /usr/libexec/PlistBuddy -c "Set :CFBundleIconName AppIcon" "$APP/Contents/Info.plist"
fi
# Ad-hoc signature so Keychain, notifications and WebKit behave like a real app. Replace with a
# Developer ID identity for distribution: CODESIGN_IDENTITY="Developer ID Application: …" scripts/build-app.sh release
codesign --force --sign "${CODESIGN_IDENTITY:--}" --entitlements "$ROOT/Resources/SuperSparrow.entitlements" "$APP" >/dev/null
echo "$APP"
